def test_tamper_missing_and_duplicate_rejected(tmp_path):
    root, project = project_fixture(tmp_path)
    bad = copy.deepcopy(project); bad["scenes"].append(bad["scenes"][0])
    with pytest.raises(ValueError): validate(root, bad)
    source = contained(root, project["assets"][0]["path"])
    source.write_bytes(b"tampered")
    with pytest.raises(ValueError, match="modified"): validate(root, project)
    source.unlink()
    with pytest.raises(ValueError, match="Missing"): validate(root, project)


def test_unknown_effect_preserved_but_blocks_prepare(tmp_path):
    root, project = project_fixture(tmp_path)
    project["effects_required"] = ["optical_motion_blur"]
    write(root / "studio.project.json", project)
    assert "optical_motion_blur" in inspect(root, project)["unsupported"]
    with pytest.raises(ValueError, match="Unsupported required"):
        prepare(root, tmp_path / "build", draft=True)
    assert not (tmp_path / "build").exists()


