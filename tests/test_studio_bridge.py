@pytest.mark.skipif(not shutil.which("ffmpeg") or not shutil.which("ffprobe"), reason="media tools unavailable")
def test_real_media_reflow_and_flow3_inputs(tmp_path):
    root = tmp_path / "input"; root.mkdir()
    image = root / "still.png"
    voice = root / "voice.wav"
    run(["ffmpeg", "-v", "error", "-f", "lavfi", "-i", "color=c=blue:s=128x128", "-frames:v", "1", image])
    run(["ffmpeg", "-v", "error", "-f", "lavfi", "-i", "sine=frequency=440:duration=1.5", "-ar", "24000", "-ac", "1", voice])
    project = {"schema": SCHEMA, "project_id": "ai-fixture", "producer": "kaggle_ai_video",
               "aspect_ratio": "1:1", "fps": 24, "assets": [], "scenes": [], "cues": [], "effects_required": []}
    aid = register(root, project, image, "still")
    vid = register(root, project, voice, "final_narration")
    project["scenes"] = [{"scene_id": "scene_001", "asset_id": aid, "duration_s": 1,
                          "narration": "Xin chào", "text_effect": "fade", "final_audio_id": vid},
                         {"scene_id": "scene_002", "asset_id": aid, "duration_s": 1, "narration": "", "text_effect": "fade"}]
    register(root, project, voice, "sfx")
    add_cue(project, vid, "sfx", "scene_002", offset_s=0.1, duration_s=0.3)
    write(root / "studio.project.json", project)
    before = {p.relative_to(root).as_posix(): p.read_bytes() for p in root.rglob("*") if p.is_file()}
    output = tmp_path / "prepared"
    report = prepare(root, output)
    assert report["duration_s"] == pytest.approx(2.5, abs=0.02)
    assert report["scenes"][1]["start_s"] == pytest.approx(1.5, abs=0.02)
    assert not report["rendered"]
    assert read(output / "flow2_package.json")["preprocess_speed"] == 1
    audio = read(output / "flow3.project.json")["metadata"]["subtitle_style"]["studio_audio"]
    assert audio[1]["start_s"] == pytest.approx(1.6, abs=0.02)
    streams = probe(output / "working.mp4")["streams"]
    assert streams[0]["width"] == 720
    assert not any(s["codec_type"] == "audio" for s in streams)
    assert before == {p.relative_to(root).as_posix(): p.read_bytes() for p in root.rglob("*") if p.is_file()}
