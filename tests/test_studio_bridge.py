def test_profile_refresh_preserves_cues_and_invalidates_changed_voice(tmp_path):
    root, project = project_fixture(tmp_path)
    voice = root / "voice.wav"; voice.write_bytes(b"audio")
    project["scenes"][0]["final_audio_id"] = register(root, project, voice, "final_narration")
    write(root / "studio.project.json", project)
    assert from_preview(root)["scenes"][0].get("final_audio_id")
    profile = read(root / "preview_profile.json")
    profile["scenes"][0]["narration"] = "Nội dung mới"
    write(root / "preview_profile.json", profile)
    assert not from_preview(root)["scenes"][0].get("final_audio_id")


