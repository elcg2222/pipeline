def project_fixture(tmp_path):
    root = tmp_path / "project"
    root.mkdir()
    (root / "image.png").write_bytes(b"test-image")
    write(root / "preview_profile.json", {"project_id": "fixture", "aspect_ratio": "9:16", "scenes": [
        {"scene_id": "scene_001", "media": "image.png", "narration": "Xin chào", "estimated_duration_sec": 1, "text_effect": "fade"}]})
    return root, from_preview(root)


def test_roundtrip_bundle_deduplicates_and_excludes_config(tmp_path):
    root, project = project_fixture(tmp_path)
    sfx = root / "pop.wav"; sfx.write_bytes(b"test-audio")
    aid = register(root, project, sfx, "sfx")
    assert register(root, project, sfx, "music") == aid
    add_cue(project, aid, "sfx", "scene_001", duration_s=0.2)
    add_cue(project, aid, "sfx", "scene_001", offset_s=0.4, duration_s=0.2)
    write(root / "studio.project.json", project)
    (root / "config.yaml").write_text("SECRET=fixture", encoding="utf-8")
    bundle = tmp_path / "bundle.zip"
    report = export_bundle(root, bundle)
    assert report["package_ready"] and not report["render_ready"]
    with zipfile.ZipFile(bundle) as z:
        assert "config.yaml" not in z.namelist()
        assert len([n for n in z.namelist() if n.startswith("resources/audio/")]) == 1
        z.extractall(tmp_path / "relocated")  # trusted archive generated by this test
    moved = tmp_path / "relocated"
    assert validate(moved, read(moved / "studio.project.json"))["package_ready"]
    assert len(read(moved / "studio.project.json")["cues"]) == 2
    with pytest.raises(FileExistsError): export_bundle(root, bundle)


